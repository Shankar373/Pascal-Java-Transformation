"""Generate ``THIRD_PARTY_NOTICES.md`` from primary sources.

Python runtime/test dependencies come from installed distribution metadata and
their shipped licence files; npm dependencies from ``frontend/package-lock.json``
and the licence files in ``frontend/node_modules`` (run ``npm ci`` first).
Nothing is fetched from the network.  Usage::

    python tools/release/generate_notices.py            # rewrite the file
    python tools/release/generate_notices.py --check    # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import json
import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "THIRD_PARTY_NOTICES.md"
FRONTEND = REPO / "frontend"
_PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s#]+)")
_COPYRIGHT = re.compile(r"^\s*(?:Copyright|\(c\)).*$", re.IGNORECASE | re.MULTILINE)

HEADER = """# Third-party notices

This file lists third-party software that this repository **depends on, bundles
or invokes**, with the licence read from each component's own metadata or
licence file. It is generated by `tools/release/generate_notices.py`
(`--check` fails when it is stale; `tests/unit/test_notices.py` runs that check).

**This is not a statement of the licence of this repository.** The Pascal repository
has no root `LICENSE` file and no licence has been selected; see
[`docs/decisions/0006-pascal-repository-licence-unresolved.md`](docs/decisions/0006-pascal-repository-licence-unresolved.md).

"""

EXTERNAL = """## Components used out of process or by reference (not vendored here)

| Component | Licence | How it is used | Obligation handling |
|---|---|---|---|
| Free Pascal Compiler 3.2.2 | GPL (compiler, sources GPLv2+) | External executable invoked by P0 sweep scripts; never linked or redistributed | ADR 0002 decision 1 |
| Free Pascal RTL/packages 3.2.2 | LGPL with linking exception | Linked into the *test programs it compiles*, not into this repository | ADR 0002 decision 4 |
| DelphiAST `3840253` | MPL-2.0 | Separate process in the P0 parser evaluation; **only a diff is committed** (`docs/p0/evidence/delphiast-fpc-helper-recursion.patch`), which is the MPL source-availability record for our modification | ADR 0002 decision 2 |
| tree-sitter-pascal `042119e` | MIT, copyright holders as in its `LICENSE` | Cloned and exercised by the P0 sweeps; no source committed here. If it is ever vendored or linked, its `LICENSE` text must be added below | ADR 0002 decision 3 |
| Delphi / RAD Studio | Proprietary | Not used or redistributed; a customer-supplied licence would be required for Stage 5 | ADR 0002 decision 5 |
| Git | GPL-2.0 | External executable invoked for Git ingestion; never linked | — |

Deliberately **not** used from the sibling COBOL repository: GnuCOBOL (GPL-3.0/LGPL-3.0) and
Berkeley DB (Sleepycat). No code was copied from that repository
(`docs/reuse/COBOL_REUSE_AUDIT.md`), so no Apache-2.0 attribution is owed at present.

"""


def license_text(dist: metadata.Distribution) -> str:
    for file in dist.files or []:
        name = file.name.upper()
        if name.startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")) and "licenses" in str(file).lower() + "licenses":
            try:
                return Path(dist.locate_file(file)).read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
    return ""


def copyright_line(text: str) -> str:
    match = _COPYRIGHT.search(text)
    return match.group(0).strip() if match else "(see the component's licence file)"


def spdx(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    value = meta.get("License-Expression") or meta.get("License") or ""
    if not value or len(value) > 60:
        for classifier in meta.get_all("Classifier", []):
            if classifier.startswith("License ::"):
                return classifier.split("::")[-1].strip()
    return value.strip() or "UNKNOWN"


def read_pins(path: Path) -> list[tuple[str, str]]:
    pins = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = _PIN.match(line.strip())
        if match:
            pins.append((match.group(1), match.group(2)))
    return pins


def python_section() -> str:
    runtime = read_pins(REPO / "requirements-api.txt")
    names = {n.lower().replace("_", "-") for n, _ in runtime}
    test_only = [("httpx", "0.28.1"), ("httpcore", "1.0.9"), ("certifi", None), ("pytest", None)]
    rows = ["## Python runtime dependencies (`requirements-api.txt`, installed by the operator, not redistributed here)\n",
            "| Package | Version | Licence | Copyright |", "|---|---|---|---|"]
    for name, version in runtime:
        dist = metadata.distribution(name)
        rows.append(f"| {name} | {version} | {spdx(dist)} | {copyright_line(license_text(dist))} |")
    rows += ["", "## Python test-only dependencies (`requirements-dev.txt`; never part of a deployment)\n",
             "| Package | Version | Licence | Note |", "|---|---|---|---|"]
    for name, _ in test_only:
        if name.lower() in names:
            continue
        dist = metadata.distribution(name)
        note = ("MPL-2.0: used unmodified as a test-time transitive dependency of httpx"
                if name == "certifi" else "")
        rows.append(f"| {name} | {dist.version} | {spdx(dist)} | {note} |")
    return "\n".join(rows) + "\n\n"


def npm_section() -> str:
    lock = json.loads((FRONTEND / "package-lock.json").read_text(encoding="utf-8"))
    package = json.loads((FRONTEND / "package.json").read_text(encoding="utf-8"))
    packages = lock["packages"]
    bundled: dict[str, dict] = {}

    def walk(name: str) -> None:
        entry = packages.get(f"node_modules/{name}")
        if entry is None or name in bundled:
            return
        bundled[name] = entry
        for dep in entry.get("dependencies", {}):
            walk(dep)

    for dep in package["dependencies"]:
        walk(dep)
    out = ["## npm packages shipped in the React bundle (`frontend/dist`) — full licence texts\n"]
    for name in sorted(bundled):
        entry = bundled[name]
        text = ""
        for candidate in ("LICENSE", "LICENSE.md", "LICENSE.txt"):
            path = FRONTEND / "node_modules" / name / candidate
            if path.is_file():
                text = path.read_text(encoding="utf-8", errors="replace").strip()
                break
        out.append(f"### {name} {entry['version']} — {entry.get('license', 'UNKNOWN')}\n")
        out.append("```text\n" + (text or "LICENSE FILE NOT FOUND — run `npm ci` and regenerate") + "\n```\n")
    counts = Counter(v.get("license", "UNKNOWN") for k, v in packages.items()
                     if k and k.removeprefix("node_modules/") not in bundled)
    out.append("## npm build/test-only packages (not shipped in the bundle)\n")
    out.append("`frontend/package-lock.json` lists these by SPDX licence (versions pinned there): "
               + ", ".join(f"{lic} × {n}" for lic, n in sorted(counts.items())) + ". "
               "Notable non-MIT entries: TypeScript (Apache-2.0), `caniuse-lite` data "
               "(CC-BY-4.0, build-time browser data only), BlueOak-1.0.0 and ISC utilities.\n")
    return "\n".join(out) + "\n"


def render() -> str:
    return HEADER + EXTERNAL + python_section() + npm_section()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("THIRD_PARTY_NOTICES.md is stale; run tools/release/generate_notices.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
